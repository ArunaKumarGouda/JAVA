// Arithmetic operations are mathematical operations performed on numbers using operators such as +, -, *, /, and %.

public class Aru_09_Arithmetic_Operators {
    public static void main(String[] args) {
        int p = 20, q = 9;

        System.out.println("Add : " + (p + q));
        System.out.println("sub : " + (p - q));
        System.out.println("mul : " + (p * q));
        System.out.println("div : " + (p / q));
        System.out.println("mod : " + (p % q));
    }
}
