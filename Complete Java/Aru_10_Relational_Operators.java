// Relational operators are used to compare two values and return either true or false

public class Aru_10_Relational_Operators {
    public static void main(String[] args) {

        int p = 10, q = 15;

        System.out.println(p == q);
        System.out.println(p != q);
        System.out.println(p <= q);
        System.out.println(p >= q);
        System.out.println(p < q);
        System.out.println(p > q);
    }
}
